                    try {
                        const val = localStorage.getItem(key);
                        return val ? JSON.parse(val) : defaultVal;
                    } catch (e) {
                        return defaultVal;
                    }
                },
                set: function(key, val) {
                    try {
                        localStorage.setItem(key, JSON.stringify(val));
