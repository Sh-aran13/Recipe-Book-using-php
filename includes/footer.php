                const bottomNavBadge = document.getElementById('bottomNavFavBadge');

                if (headerBadge) {
                    if (count > 0) {
                        headerBadge.textContent = count;
                        headerBadge.style.display = 'inline-flex';
                    } else {
                        headerBadge.style.display = 'none';
                    }
                }
                if (sidebarBadge) {
                    if (count > 0) {
                        sidebarBadge.textContent = count;
                        sidebarBadge.style.display = 'inline-flex';
                    } else {
                        sidebarBadge.style.display = 'none';
                    }
                }
                if (bottomNavBadge) {
                    if (count > 0) {
                        bottomNavBadge.textContent = count;
                        bottomNavBadge.style.display = 'inline-block';
                    } else {
                        bottomNavBadge.style.display = 'none';
                    }
                }

                // Update any favorite buttons on the page (supports [data-fav-id], [data-recipe-id], .js-fav-btn)
                document.querySelectorAll('[data-fav-id], [data-recipe-id], .js-fav-btn, .btn-fav-card').forEach(function(btn) {
                    const id = String(btn.getAttribute('data-fav-id') || btn.getAttribute('data-recipe-id') || '');
                    if (!id) return;
                    const isFaved = favs.includes(id);
                    if (isFaved) {
                        btn.classList.add('is-fav');
                        btn.setAttribute('aria-label', 'Remove from favorites');
                        btn.setAttribute('title', 'Remove from favorites');
                        if (btn.classList.contains('rcard-fav') || btn.classList.contains('js-fav-btn')) {
                            btn.textContent = '♥';
                        }
                    } else {
                        btn.classList.remove('is-fav');
                        btn.setAttribute('aria-label', 'Save to favorites');
                        btn.setAttribute('title', 'Save to favorites');
                        if (btn.classList.contains('rcard-fav') || btn.classList.contains('js-fav-btn')) {
                            btn.textContent = '♡';
                        }
                    }
                });
            }

            // Global click handler for favorite buttons with immediate visual update
            document.addEventListener('click', function(e) {
                const btn = e.target.closest('[data-fav-id], [data-recipe-id], .js-fav-btn, .btn-fav-card');
                if (!btn) return;

                const id = String(btn.getAttribute('data-fav-id') || btn.getAttribute('data-recipe-id') || '');
                if (!id) return;

                e.preventDefault();
                e.stopPropagation();

                let favs = (storage.get('amma_fav_recipes', null) || storage.get('amma_favorites', [])).map(String);
                const idx = favs.indexOf(id);

                if (idx > -1) {
                    favs.splice(idx, 1);
                    btn.classList.remove('is-fav');
                    if (btn.classList.contains('rcard-fav') || btn.classList.contains('js-fav-btn')) {
                        btn.textContent = '♡';
                    }
                } else {
                    favs.push(id);
                    btn.classList.add('is-fav');
                    if (btn.classList.contains('rcard-fav') || btn.classList.contains('js-fav-btn')) {
                        btn.textContent = '♥';
                    }
                }

                // Keep unique values and save to both keys
                const uniqueFavs = Array.from(new Set(favs));
                storage.set('amma_fav_recipes', uniqueFavs);
                storage.set('amma_favorites', uniqueFavs);

                updateFavBadges();

                // Trigger custom event for favorites.php or other components
                window.dispatchEvent(new CustomEvent('amma_favorites_updated', { detail: { favorites: uniqueFavs } }));
            });

            // Initialize on DOM ready
            updateFavBadges();

            // Expose helper globally
            window.AmmaStorage = storage;
            window.updateAmmaFavBadges = updateFavBadges;
        })();
    </script>
